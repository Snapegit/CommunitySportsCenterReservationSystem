				yonghuming: '',
				yuyueshijian: '',
			},
		
			changdishuliangOptions: [],

			
			rules: {
				dingdanbianhao: [
				],
				changguanmingcheng: [
				],
				tupian: [
				],
				changdileixing: [
				],
				changdishuliang: [
					{ validator: validateIntNumber, trigger: 'blur' },
				],
				rongnarenshu: [
				],
				yuyueshizhang: [
					{ validator: validateIntNumber, trigger: 'blur' },
				],
				jiage: [
					{ required: true, message: '价格不能为空', trigger: 'blur' },
					{ validator: validateNumber, trigger: 'blur' },
				],
				huiyuanzhekou: [
					{ validator: validateNumber, trigger: 'blur' },
				],
				shifujine: [
					{ validator: validateNumber, trigger: 'blur' },
				],
				yonghuming: [
				],
				yuyueshijian: [
				],
				ispay: [
				],
			}
		};
	},
	props: ["parent"],
	computed: {


		shifujine:{
			get: function () {
				return 1*this.ruleForm.yuyueshizhang*this.ruleForm.jiage*this.ruleForm.huiyuanzhekou
			}
		},

	},
    components: {
    },
	created() {
		this.ruleForm.yuyueshijian = this.getCurDateTime()
	},
	methods: {
		
		// 下载
		download(file){
			window.open(`${file}`)
		},
		// 初始化
		init(id,type) {
			if (id) {
				this.id = id;
				this.type = type;
			}
			if(this.type=='info'||this.type=='else'){
				this.info(id);
			}else if(this.type=='logistics'){
				this.logistics=false;
				this.info(id);
			}else if(this.type=='cross'){
				var obj = this.$storage.getObj('crossObj');
				for (var o in obj){
						if(o=='dingdanbianhao'){
							this.ruleForm.dingdanbianhao = obj[o];
							this.ro.dingdanbianhao = true;
							continue;
						}
						if(o=='changguanmingcheng'){
							this.ruleForm.changguanmingcheng = obj[o];
							this.ro.changguanmingcheng = true;
							continue;
						}
						if(o=='tupian'){
							this.ruleForm.tupian = obj[o];
							this.ro.tupian = true;
							continue;
						}
						if(o=='changdileixing'){
							this.ruleForm.changdileixing = obj[o];
							this.ro.changdileixing = true;
							continue;
						}
						if(o=='changdishuliang'){
							this.ruleForm.changdishuliang = obj[o];
							this.ro.changdishuliang = true;
							continue;
						}
						if(o=='rongnarenshu'){
							this.ruleForm.rongnarenshu = obj[o];
							this.ro.rongnarenshu = true;
							continue;
