						if(o=='shifujine'){
							this.ruleForm.shifujine = obj[o];
							this.ro.shifujine = true;
							continue;
						}
						if(o=='yonghuming'){
							this.ruleForm.yonghuming = obj[o];
							this.ro.yonghuming = true;
							continue;
						}
						if(o=='yuyueshijian'){
							this.ruleForm.yuyueshijian = obj[o];
							this.ro.yuyueshijian = true;
							continue;
						}
				}
				this.ruleForm.changdishuliang = 0
				this.ro.changdishuliang = false;
				this.ruleForm.changdishuliang = Number('1'); 			}
			// 获取用户信息
			this.$http({
				url: `${this.$storage.get('sessionTable')}/session`,
				method: "get"
			}).then(({ data }) => {
				if (data && data.code === 0) {
					var json = data.data;
					if(((json.huiyuanzhekou!=''&&json.huiyuanzhekou) || json.huiyuanzhekou==0) && this.$storage.get("role")!="管理员"){
						this.ruleForm.huiyuanzhekou = json.huiyuanzhekou
