	isNumber,
	isIntNumer,
} from "@/utils/validate";
export default {
	data() {
		var validateNumber = (rule, value, callback) => {
			if(!value){
				callback();
			} else if (!isNumber(value)) {
				callback(new Error("请输入数字"));
			} else {
				callback();
			}
		};
		var validateIntNumber = (rule, value, callback) => {
			if(!value){
				callback();
			} else if (!isIntNumer(value)) {
				callback(new Error("请输入整数"));
			} else {
				callback();
			}
		};
		return {
			id: '',
			type: '',
			
			
			ro:{
				dingdanbianhao : false,
				changguanmingcheng : false,
				tupian : false,
				changdileixing : false,
				changdishuliang : false,
				rongnarenshu : false,
				yuyueshizhang : false,
				jiage : false,
				huiyuanzhekou : false,
				shifujine : false,
				yonghuming : false,
				yuyueshijian : false,
				ispay : false,
			},
			
			
			ruleForm: {
				dingdanbianhao: this.getUUID(),
				changguanmingcheng: '',
				tupian: '',
				changdileixing: '',
				changdishuliang: '1',
				rongnarenshu: '',
				yuyueshizhang: '',
				jiage: '',
				huiyuanzhekou: '',
